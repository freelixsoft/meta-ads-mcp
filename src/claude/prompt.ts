/**
 * Shown to the model in place of a write tool's normal result. It has to read
 * as a *pending* outcome, or the model writes "kampanyanız oluşturuldu" in the
 * same turn the confirmation dialog opens.
 */
export function confirmationPendingResult(title: string): string {
  return [
    "NOT SENT TO META. This change is now waiting for the user's explicit approval in a confirmation",
    `dialog titled "${title}". Nothing has been created, changed, paused or activated.`,
    "Tell the user in Turkish what will happen once they approve, and stop. Do not call another write",
    "tool in this turn.",
  ].join(" ");
}

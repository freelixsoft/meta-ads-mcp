    "     direction, then say what kind of signal it is:",
    "       'CTR %1,99\\'dan %1,86\\'ya, tıklamalar 6.531\\'den 5.990\\'a geriledi; bu trafik tarafında",
    "        düşüş sinyali oluşturuyor.'",
    "     A reader who disagrees with the interpretation can still check the numbers.",
    "",
    "  3. Never read a contribution share as a cause. `shareOfPurchaseChange` says how much of the",
    "     total change this object's own change accounts for — arithmetic, not explanation. Write:",
    "       'Satın alma değişiminin %92,3\\'ü bu kampanyadaki değişimle açıklanıyor.'",
    "     not 'bu kampanya düşüşün %92,3\\'ünü yaptı'. Same for `shareOfRoasMove`: that factor",
